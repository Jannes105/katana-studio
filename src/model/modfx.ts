// Parameters of the mod and FX blocks (protocol-notes 2.8, "Blocks for Phase 2"): 225 bytes per variation, one
// layout for both effects and all 31 types, every type at its own fixed offsets (PLAN 4.4: no overlay, only a
// visibility rule). Offsets, ranges, labels and value tables are our own table, taken from the local analysis of
// BOSS Tone Studio (which knob shows on which type page). Checked on the amp 2026-11-17 (-ParamTest -NoAsk
// -AllTypes, mod and FX variation 0: written, read back, no other byte changed, restored).

import type { ParamDef } from './schema';
import { EQ_FREQ, EQ_Q, HIGH_CUT, LOW_CUT, OFF_ON } from './tables';

type Rest = Partial<ParamDef> & Pick<ParamDef, 'min' | 'max' | 'control'>;

/** One byte inside the mod/FX block. */
function fx(key: string, label: string, byte: number, rest: Rest): ParamDef {
  return { key, label, at: byte, encoding: 'u7', status: 'C', ...rest };
}

/** Four nibbles (u4x4) inside the mod/FX block: pre delays and the DC-30 echo rate. */
function fx4(key: string, label: string, byte: number, rest: Rest): ParamDef {
  return { key, label, at: byte, encoding: 'u4x4', dragStep: 1, status: 'C', ...rest };
}

